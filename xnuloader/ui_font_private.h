static inline uint32_t
ui_blend(uint32_t bg, uint32_t fg, uint32_t a)
{
	if (a == 0) return bg & 0x00ffffffu;
	if (a >= 256) return fg & 0x00ffffffu;
	uint32_t inv = 256 - a;
	uint32_t rb = (((fg & 0x00ff00ffu) * a + (bg & 0x00ff00ffu) * inv) >> 8) & 0x00ff00ffu;
	uint32_t g  = (((fg & 0x0000ff00u) * a + (bg & 0x0000ff00u) * inv) >> 8) & 0x0000ff00u;
	return rb | g;
}

static inline void
ui_put_px(int x, int y, uint32_t color)
{
	if (SCREEN.base == 0 || x < 0 || y < 0 || x >= (int)SCREEN.width || y >= (int)SCREEN.height) {
		return;
	}
	volatile uint32_t *fb = (volatile uint32_t *)(uintptr_t)SCREEN.base;
	fb[(unsigned)y * (SCREEN.stride / 4) + (unsigned)x] = color & 0x00ffffffu;
}

static void
ui_fill(int x, int y, int w, int h, uint32_t color)
{
	volatile uint32_t *fb;
	unsigned stride;
	int x1 = x + w, y1 = y + h;

	if (SCREEN.base == 0 || w <= 0 || h <= 0) {
		return;
	}
	if (x < 0) x = 0;
	if (y < 0) y = 0;
	if (x1 > (int)SCREEN.width) x1 = (int)SCREEN.width;
	if (y1 > (int)SCREEN.height) y1 = (int)SCREEN.height;
	color &= 0x00ffffffu;
	uint64_t pair = (uint64_t)color | ((uint64_t)color << 32);
	fb = (volatile uint32_t *)(uintptr_t)SCREEN.base;
	stride = SCREEN.stride / 4;
	for (int row = y; row < y1; row++) {
		volatile uint32_t *line = fb + (unsigned)row * stride;
		int col = x;
		if ((((uintptr_t)(line + (unsigned)col)) & 7u) != 0 && col < x1) {
			line[(unsigned)col++] = color;
		}
		for (; col + 1 < x1; col += 2) {
			*(volatile uint64_t *)(line + (unsigned)col) = pair;
		}
		if (col < x1) {
			line[(unsigned)col] = color;
		}
	}
}

/*
 * Anti-aliased rounded rectangle with optional border, evaluated via integer
 * signed-distance approximation in 2x subpixel coordinates.
 */
static void
ui_round_rect(int x, int y, int w, int h, int r, int border, uint32_t fill_col, uint32_t border_col, uint32_t bg_col)
{
	if (SCREEN.base == 0 || w <= 0 || h <= 0) {
		return;
	}
	if (r * 2 > w) r = w / 2;
	if (r * 2 > h) r = h / 2;
	if (r < 1) {
		if (border > 0) {
			ui_fill(x, y, w, h, border_col);
			ui_fill(x + border, y + border, w - 2 * border, h - 2 * border, fill_col);
		} else {
			ui_fill(x, y, w, h, fill_col);
		}
		return;
	}

	volatile uint32_t *fb = (volatile uint32_t *)(uintptr_t)SCREEN.base;
	unsigned stride = SCREEN.stride / 4;
	int R2 = 2 * r;
	int Rout_lo2 = (R2 - 1) * (R2 - 1);
	int Rout_hi2 = (R2 + 1) * (R2 + 1);
	int Rout_span = Rout_hi2 - Rout_lo2 > 0 ? Rout_hi2 - Rout_lo2 : 1;

	int Rin2 = 2 * (r - border);
	int Rin_lo2 = Rin2 > 1 ? (Rin2 - 1) * (Rin2 - 1) : 0;
	int Rin_hi2 = Rin2 > 0 ? (Rin2 + 1) * (Rin2 + 1) : 0;
	int Rin_span = Rin_hi2 - Rin_lo2 > 0 ? Rin_hi2 - Rin_lo2 : 1;

	int y0 = y < 0 ? 0 : y;
	int y1 = (y + h) > (int)SCREEN.height ? (int)SCREEN.height : (y + h);
	int x0 = x < 0 ? 0 : x;
	int x1 = (x + w) > (int)SCREEN.width ? (int)SCREEN.width : (x + w);

	for (int row = y0; row < y1; row++) {
		int ry = row - y;
		int in_corner_y = (ry < r) || (ry >= h - r);
		volatile uint32_t *line = fb + (unsigned)row * stride;

		if (!in_corner_y) {
			int mid_h = (y + h - r < y1 ? y + h - r : y1) - row;
			if (border > 0) {
				ui_fill(x, row, border, mid_h, border_col);
				ui_fill(x + border, row, w - 2 * border, mid_h, fill_col);
				ui_fill(x + w - border, row, border, mid_h, border_col);
			} else {
				ui_fill(x, row, w, mid_h, fill_col);
			}
			row += mid_h - 1;
			continue;
		}

		int dy2 = (ry < r) ? (2 * r - 1 - 2 * ry) : (2 * (ry - (h - r)) + 1);
		dy2 = dy2 * dy2;

		for (int col = x0; col < x1; col++) {
			int rx = col - x;
			if (rx >= r && rx < w - r) {
				int span_end = (x + w - r < x1) ? (x + w - r) : x1;
				uint32_t c = (border > 0 && (ry < border || ry >= h - border)) ? border_col : fill_col;
				ui_fill(col, row, span_end - col, 1, c);
				col = span_end - 1;
				continue;
			}
			int dx = (rx < r) ? (2 * r - 1 - 2 * rx) : (2 * (rx - (w - r)) + 1);
			int d2 = dx * dx + dy2;

			uint32_t out_a;
			if (d2 <= Rout_lo2) out_a = 256;
			else if (d2 >= Rout_hi2) out_a = 0;
			else out_a = (uint32_t)((Rout_hi2 - d2) * 256 / Rout_span);

			if (out_a == 0) {
				line[(unsigned)col] = bg_col & 0x00ffffffu;
				continue;
			}

			uint32_t inner_col = fill_col;
			if (border > 0) {
				if (Rin2 <= 0) {
					inner_col = border_col;
				} else {
					uint32_t in_a;
					if (d2 <= Rin_lo2) in_a = 256;
					else if (d2 >= Rin_hi2) in_a = 0;
					else in_a = (uint32_t)((Rin_hi2 - d2) * 256 / Rin_span);
					inner_col = ui_blend(border_col, fill_col, in_a);
				}
			}
			line[(unsigned)col] = ui_blend(bg_col, inner_col, out_a);
		}
	}
}

static inline uint32_t
ui_glyph_cov(const uint64_t *rows, int c, int r)
{
	if (c < 0 || c >= UI_GLYPH_W || r < 0 || r >= UI_GLYPH_H) return 0;
	uint32_t q = (uint32_t)((rows[r] >> (2 * (UI_GLYPH_W - 1 - c))) & 3ULL);
	return q == 3 ? 256 : (q * 85);
}

static inline uint32_t
ui_icon_cov(const uint64_t *rows, int c, int r)
{
	if (c < 0 || c >= 32 || r < 0 || r >= 32) return 0;
	uint32_t q = (uint32_t)((rows[r] >> (2 * (31 - c))) & 3ULL);
	return q == 3 ? 256 : (q * 85);
}

/*
 * Draw anti-aliased text using 2-bit SF Pro glyphs with bilinear upscaling.
 */
static void
ui_draw_text_ex(int x, int y, const char *s, int scale, int max_chars, uint32_t fg, uint32_t bg, int clip_card, int bold)
{
	if (SCREEN.base == 0 || s == NULL || scale <= 0) {
		return;
	}
	int num = (scale <= 1) ? 4 : (scale == 2 ? 5 : (scale == 3 ? 7 : scale * 2));
	int den = 4;
	int cx = x;
	int out_h = (UI_GLYPH_H * num) / den;
	int max_x = clip_card ? ((int)SCREEN.width - 96) : (int)SCREEN.width;
	(void)bg;

	for (int n = 0; n < max_chars && s[n]; n++) {
		unsigned char u = (unsigned char)s[n];
		if (u < 0x20 || u > 0x7e) u = '?';
		int idx = (int)(u - 0x20);
		const uint64_t *g = ui_font_20x26[idx];
		int adv = ((int)ui_font_adv[idx] * num + den / 2) / den;
		if (cx + adv > max_x) {
			break;
		}

		if (u != ' ') {
			int out_w = (UI_GLYPH_W * num) / den + 2;
			for (int py = 0; py < out_h; py++) {
				int sy_fp = (py * den * 16) / num;
				int r0 = sy_fp >> 4;
				int fy = sy_fp & 15;
				for (int px = 0; px < out_w; px++) {
					int sx_fp = (px * den * 16) / num;
					int c0 = sx_fp >> 4;
					int fx = sx_fp & 15;
					uint32_t v00 = ui_glyph_cov(g, c0, r0);
					uint32_t v10 = ui_glyph_cov(g, c0 + 1, r0);
					uint32_t v01 = ui_glyph_cov(g, c0, r0 + 1);
					uint32_t v11 = ui_glyph_cov(g, c0 + 1, r0 + 1);
					uint32_t top = (v00 * (16 - fx) + v10 * fx) >> 4;
					uint32_t bot = (v01 * (16 - fx) + v11 * fx) >> 4;
					uint32_t a = (top * (16 - fy) + bot * fy) >> 4;
					if (bold && px > 0) {
						int sx_prev = ((px - 1) * den * 16) / num;
						int cp = sx_prev >> 4, fxp = sx_prev & 15;
						uint32_t ptop = (ui_glyph_cov(g, cp, r0) * (16 - fxp) + ui_glyph_cov(g, cp + 1, r0) * fxp) >> 4;
						uint32_t pbot = (ui_glyph_cov(g, cp, r0 + 1) * (16 - fxp) + ui_glyph_cov(g, cp + 1, r0 + 1) * fxp) >> 4;
						uint32_t pa = (ptop * (16 - fy) + pbot * fy) >> 4;
						if (pa > a) a = (a + pa) >> 1 > a ? (a + pa) >> 1 : pa;
					}
					if (a > 0) {
						int dst_x = cx + px;
						int dst_y = y + py;
						ui_put_px(dst_x, dst_y, ui_blend(bg, fg, a));
					}
				}
			}
		}
		cx += adv;
	}
}

static int
ui_measure_text_ex(const char *s, int max_chars, int scale, int unused_mono)
{
	if (s == NULL || scale <= 0) return 0;
	int num = (scale <= 1) ? 4 : (scale == 2 ? 5 : (scale == 3 ? 7 : scale * 2));
	int den = 4;
	int total = 0;
	(void)unused_mono;

	for (int n = 0; n < max_chars && s[n]; n++) {
		unsigned char u = (unsigned char)s[n];
		if (u < 0x20 || u > 0x7e) u = '?';
		int idx = (int)(u - 0x20);
		total += ((int)ui_font_adv[idx] * num + den / 2) / den;
	}
	return total;
}

static void
ui_draw_icon24(int x, int y, const uint64_t *icon, int scale, uint32_t fg, uint32_t bg)
{
	if (SCREEN.base == 0 || icon == NULL || scale <= 0) return;
	(void)bg;
	int out_sz = 24 * scale;
	for (int py = 0; py < out_sz; py++) {
		int sy_fp = (py * 32 * 16) / out_sz;
		int r0 = sy_fp >> 4, fy = sy_fp & 15;
		for (int px = 0; px < out_sz; px++) {
			int sx_fp = (px * 32 * 16) / out_sz;
			int c0 = sx_fp >> 4, fx = sx_fp & 15;
			uint32_t v00 = ui_icon_cov(icon, c0, r0);
			uint32_t v10 = ui_icon_cov(icon, c0 + 1, r0);
			uint32_t v01 = ui_icon_cov(icon, c0, r0 + 1);
			uint32_t v11 = ui_icon_cov(icon, c0 + 1, r0 + 1);
			uint32_t top = (v00 * (16 - fx) + v10 * fx) >> 4;
			uint32_t bot = (v01 * (16 - fx) + v11 * fx) >> 4;
			uint32_t a = (top * (16 - fy) + bot * fy) >> 4;
			if (a > 0) {
				ui_put_px(x + px, y + py, ui_blend(bg, fg, a));
			}
		}
	}
}

/*
 * Anti-aliased rotating comet-ring spinner (16 angular steps).
 */
static void
ui_draw_spinner_ring(int cx, int cy, int r_outer, int thickness, int phase, uint32_t fg_col, uint32_t track_col, uint32_t bg_col)
{
	static const int16_t dir_x[16] = {
		   0,   98,  181,  237,  256,  237,  181,   98,
		   0,  -98, -181, -237, -256, -237, -181,  -98
	};
	static const int16_t dir_y[16] = {
		-256, -237, -181,  -98,    0,   98,  181,  237,
		 256,  237,  181,   98,    0,  -98, -181, -237
	};

	if (SCREEN.base == 0 || r_outer <= thickness) return;
	int r_inner = r_outer - thickness;
	int Ro2 = 2 * r_outer;
	int Ri2 = 2 * r_inner;
	int Ro_lo2 = (Ro2 - 1) * (Ro2 - 1), Ro_hi2 = (Ro2 + 1) * (Ro2 + 1);
	int Ri_lo2 = (Ri2 - 1) * (Ri2 - 1), Ri_hi2 = (Ri2 + 1) * (Ri2 + 1);
	int Ro_span = Ro_hi2 - Ro_lo2 > 0 ? Ro_hi2 - Ro_lo2 : 1;
	int Ri_span = Ri_hi2 - Ri_lo2 > 0 ? Ri_hi2 - Ri_lo2 : 1;

	int ux = dir_x[phase & 15];
	int uy = dir_y[phase & 15];

	for (int py = cy - r_outer - 1; py <= cy + r_outer + 1; py++) {
		int dy = 2 * (py - cy);
		for (int px = cx - r_outer - 1; px <= cx + r_outer + 1; px++) {
			int dx = 2 * (px - cx);
			int d2 = dx * dx + dy * dy;
			if (d2 >= Ro_hi2 || d2 <= Ri_lo2) {
				ui_put_px(px, py, bg_col);
				continue;
			}
			uint32_t oa = (d2 <= Ro_lo2) ? 256 : (uint32_t)((Ro_hi2 - d2) * 256 / Ro_span);
			uint32_t ia = (d2 >= Ri_hi2) ? 256 : (uint32_t)((d2 - Ri_lo2) * 256 / Ri_span);
			uint32_t ring_a = (oa * ia) >> 8;

			int along = (dx * ux + dy * uy) / (r_outer > 0 ? r_outer : 1);
			int perp  = (dx * uy - dy * ux) / (r_outer > 0 ? r_outer : 1);
			uint32_t comet_a = 0;
			if (perp >= 0) {
				int t = 160 + (along * 96) / 512;
				if (t < 0) t = 0;
				if (t > 256) t = 256;
				comet_a = (uint32_t)t;
			} else if (along > 380) {
				comet_a = (uint32_t)((along - 380) * 256 / 132);
				if (comet_a > 256) comet_a = 256;
			}
			uint32_t ring_col = ui_blend(track_col, fg_col, comet_a);
			ui_put_px(px, py, ui_blend(bg_col, ring_col, ring_a));
		}
	}
}

static int
ui_dec(char *out, uint64_t v)
{
	char tmp[20];
	int n = 0, i;

	do {
		tmp[n++] = (char)('0' + v % 10);
		v /= 10;
	} while (v);
	for (i = 0; i < n; i++) {
		out[i] = tmp[n - 1 - i];
	}
	return n;
}

